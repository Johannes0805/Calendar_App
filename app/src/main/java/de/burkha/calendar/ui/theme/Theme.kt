/**
 * Das Theme der ganzen App.
 *
 * dynamicColor = true  -> Material You: Farben kommen vom Wallpaper (Standard).
 * dynamicColor = false -> Die festen Farben aus Color.kt.
 *
 * Dunkelmodus folgt automatisch der Systemeinstellung.
 */
@Composable
fun CalendarTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        // minSdk ist 31, Material You ist also immer verfügbar.
        dynamicColor -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AppTypography,
        shapes = AppShapes,
        content = content,
    )
}
